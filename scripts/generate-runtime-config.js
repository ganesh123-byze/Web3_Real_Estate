const fs = require("fs");
const path = require("path");

const FRONTEND_DIR = path.resolve(__dirname, "..", "frontend");
const FRONTEND_LIB = path.join(FRONTEND_DIR, "lib");
const OUT_PATH = path.join(FRONTEND_DIR, "runtime-config.js");
const PUBLIC_OUT_PATH = path.join(FRONTEND_DIR, "public", "runtime-config.js");
const GENERATED_TS_PATH = path.join(FRONTEND_LIB, "generated-runtime-env.ts");
const CONTRACT_PATH = process.env.CONTRACT_ADDRESSES_PATH || path.resolve(__dirname, "..", "backend", "config", "contract-addresses.json");

function stripTrailingSlash(url) {
  return String(url || "").trim().replace(/\/$/, "");
}

function resolveApiBaseUrl() {
  return stripTrailingSlash(
    process.env.NEXT_PUBLIC_API_BASE_URL ||
      process.env.API_BASE_URL ||
      process.env.BACKEND_URL ||
      "",
  );
}

const apiBaseUrl = resolveApiBaseUrl();
const chainId = Number(process.env.CHAIN_ID || process.env.NEXT_PUBLIC_CHAIN_ID || 11155111);
const explorerTxBase = process.env.EXPLORER_TX_BASE || process.env.NEXT_PUBLIC_EXPLORER_TX_BASE || "https://sepolia.etherscan.io/tx/";
const deployEnv = process.env.DEPLOY_ENV || process.env.NODE_ENV || "development";

const config = {
  API_BASE_URL: apiBaseUrl,
  CHAIN_ID: chainId,
  EXPECTED_CHAIN_HEX: process.env.EXPECTED_CHAIN_HEX || `0x${chainId.toString(16)}`,
  EXPLORER_TX_BASE: explorerTxBase,
  ENV: deployEnv,
  CONTRACT_ADDRESSES: {},
};

if (!config.API_BASE_URL) {
  if (process.env.VERCEL === "1" || process.env.NETLIFY === "true") {
    console.error(
      "\n[EstateChain] Build error: backend URL is required on Vercel/Netlify.\n" +
        "  Set one of (no trailing slash):\n" +
        "    NEXT_PUBLIC_API_BASE_URL=https://your-api.onrender.com\n" +
        "    BACKEND_URL=https://your-api.onrender.com\n" +
        "    API_BASE_URL=https://your-api.onrender.com\n" +
        "  Redeploy after saving.\n"
    );
    process.exit(1);
  }
  if (deployEnv !== "production") {
    config.API_BASE_URL = "http://127.0.0.1:8000";
  }
}

if (fs.existsSync(CONTRACT_PATH)) {
  try {
    const raw = fs.readFileSync(CONTRACT_PATH, "utf8");
    config.CONTRACT_ADDRESSES = JSON.parse(raw);
  } catch (error) {
    console.warn(`Unable to read contract addresses from ${CONTRACT_PATH}:`, error.message);
  }
}

const contents = `window.__ESTATECHAIN_CONFIG__ = ${JSON.stringify(config, null, 2)};\n`;
fs.writeFileSync(OUT_PATH, contents, "utf8");
fs.mkdirSync(path.dirname(PUBLIC_OUT_PATH), { recursive: true });
fs.writeFileSync(PUBLIC_OUT_PATH, contents, "utf8");

const generatedTs = `/**
 * Auto-generated by scripts/generate-runtime-config.js — do not edit manually.
 */
export const GENERATED_API_BASE_URL = ${JSON.stringify(config.API_BASE_URL || "")};
export const GENERATED_CHAIN_ID = ${Number.isFinite(config.CHAIN_ID) ? config.CHAIN_ID : 0};
export const GENERATED_EXPLORER_TX_BASE = ${JSON.stringify(config.EXPLORER_TX_BASE || "")};
`;
fs.mkdirSync(FRONTEND_LIB, { recursive: true });
fs.writeFileSync(GENERATED_TS_PATH, generatedTs, "utf8");

console.log(`Runtime config written to ${OUT_PATH}`);
console.log(`Public runtime config written to ${PUBLIC_OUT_PATH}`);
console.log(`Generated env module written to ${GENERATED_TS_PATH}`);
